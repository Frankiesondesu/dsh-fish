/**
 * toolguide.js —— 她手边工具的使用说明（fork.44，2026-11-04）
 *
 * 为什么要有这一层：工具表的 description 必须短——它每轮都在上下文里，
 * 十三个工具各写两百字就是两三千 token 的常驻开销。但太短她就不会用：
 * 加 `her_alarm` 那天，她看到的只有一句"给自己定一个时刻"，不知道该不该用、
 * 用错了会怎样。
 *
 * 所以分两层：
 *   - 工具表里：一句话（够认出是什么）
 *   - 这个文件里：能做什么 / 不能做什么 / 被拒时是什么样（按需查，不常驻）
 *
 * ⚠️ 只写**事实**，不写"你应该在什么时候用"。她要不要用、什么时候用，
 * 是她的事；这里只回答"这东西是什么、边界在哪、失败长什么样"。
 * 一旦写成"遇到 X 就调它"，就成了替她做判断。
 */

