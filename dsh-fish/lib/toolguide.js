/** 说明书的目录：她不知道名字时先看这个。 */
export function guideIndex() {
  return Object.entries(TOOL_GUIDE).map(([name, g]) => `- ${name}：${g.brief}`)
}

/** 某一个工具的详情；没有这个工具就返回空串。 */
export function guideOf(name) {
  const key = String(name ?? '').trim()
  const g = TOOL_GUIDE[key]
  if (!g) return ''
  const lines = [`## ${key}`, g.brief, '', '能做：', ...g.can.map((s) => `- ${s}`), '', '做不到：', ...g.cant.map((s) => `- ${s}`)]
  return lines.join('\n')
}
